-- ============================================================================
-- TUT Vision — Database Schema (Phase 1)
-- ----------------------------------------------------------------------------
-- Staff-availability platform for Tshwane University of Technology.
-- PostgreSQL. Identity comes from Microsoft Entra (no passwords stored here).
--
-- HOW TO RUN (PowerShell), against the tut_vision database:
--     psql -U postgres -d tut_vision -f schema.sql
--
-- Tables are created in dependency order (parents before children) so that
-- every foreign key points at a table that already exists.
--
-- NOTE ON POPIA: raw GPS coordinates and lobby photos are never stored. We keep
-- only the on/off-campus flag and an encrypted biometric template. See the
-- geofence and biometric_enrolment sections below.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- Teardown (rebuild-from-scratch only).
-- These DROPs delete the tables AND ALL THEIR DATA. CASCADE removes anything
-- that depends on them, so order does not matter here. Leave this block
-- commented out during normal use; uncomment only when you deliberately want
-- to wipe and rebuild the whole database.
-- ----------------------------------------------------------------------------
